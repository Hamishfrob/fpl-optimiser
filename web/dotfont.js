/** The dot rows of one character: 7 strings of 5 characters, '#' is lit. Unknown characters are blank. */
export function glyphRows(ch) {
  return (G[ch.toUpperCase()] ?? G[' ']).split('/');
}

/** A whole string as one grid of 7 rows, with one blank column between characters. Returns {rows, cols}. */
export function textGrid(text) {
  const rows = Array.from({ length: 7 }, () => '');
  [...text].forEach((ch, i) => glyphRows(ch).forEach((r, y) => { rows[y] += (i ? '.' : '') + r; }));
  return { rows, cols: rows[0].length };
}
